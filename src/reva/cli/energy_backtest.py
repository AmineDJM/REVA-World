"""CLI of the EIA STEO vintage energy backtest (V6, PRED-ENERGY): ``python -m reva.cli.energy_backtest``.

Kept out of :mod:`reva.evaluation.energy_backtests` so the evaluation package never reaches the object-store
factory (invariant 11).
"""

from __future__ import annotations

import json
from collections.abc import Mapping, Sequence
from typing import Any

from reva.evaluation.energy_backtests import ALPHA, LABEL, load_and_run
from reva.models.forecasting.energy_models import NOT_ISSUABLE


def main(argv: Sequence[str] | None = None) -> int:
    import argparse

    from reva.adapters.objects.factory import get_store
    from reva.adapters.postgres.engine import make_engine
    from reva.settings import get_settings

    ap = argparse.ArgumentParser(description="EIA STEO vintage backtest (PRED-ENERGY)")
    ap.add_argument("--origin", default="live")
    ap.add_argument("--out", required=True, help="JSON result path (records included)")
    ap.add_argument("--winners", help="write the winners YAML here (registry/forecasts/energy_winners.yaml)")
    a = ap.parse_args(argv)
    eng = make_engine("api", get_settings())
    with eng.connect() as conn:
        res = load_and_run(conn, get_store(), origin=a.origin)
    with open(a.out, "w", encoding="utf-8") as fh:
        json.dump(res, fh, indent=1, default=str)
    if a.winners:
        write_winners(res, a.winners)
    print(json.dumps({"digest": res["digest"], "n_records": res["n_records"], "winners": res["winners"]}, indent=1))
    return 0


def write_winners(res: Mapping[str, Any], path: str) -> None:
    import yaml

    doc = {
        "schema": "reva-energy-winners/1",
        "backtest_label": LABEL,
        "backtest_digest": res["digest"],
        "rule": (
            f"REVA candidate whose CRPS beats the random walk (DM-HLN one-sided p, ONE Holm-Bonferroni family over "
            f"every (variable, issuable candidate, horizon) test of the run, alpha {ALPHA}) on the STEO archive "
            f"vintage backtest; EIA-derived candidates excluded from issuance: {sorted(NOT_ISSUABLE)} (FIX7)"
        ),
        "selection_note": "in-sample selection (no holdout): admission to the registry, not evidence of skill; "
        "skill is measured only on resolved prospective questions",
        "origins": [o["vintage"] for o in res["origins"]],
        "winners": [
            {
                k: w.get(k)
                for k in (
                    "code",
                    "h",
                    "model",
                    "model_key",
                    "p_challenger_better",
                    "holm_family_size",
                    "crps_ratio_vs_rw",
                    "coverage_80",
                    "ae_vs_steo_mean_diff",
                )
            }
            for w in res["winners"]
        ],
    }
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("# Generated by `python -m reva.cli.energy_backtest` (PRED-ENERGY). Do not edit by hand.\n")
        yaml.safe_dump(doc, fh, sort_keys=False, allow_unicode=True)


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
