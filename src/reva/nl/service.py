MAX_LIST = 50
MAX_STR = 1000
MAX_INDEX = 99
DEFAULT_SEED = 0
_PATH = re.compile(r"^[a-z_][a-z0-9_]*(\[\d{1,2}\])?(\.[a-z_][a-z0-9_]*(\[\d{1,2}\])?){0,5}$")
MACRO_OUTPUT_HINTS = ("gdp", "pib", "unemploy", "chomage", "chômage", "inflation", "welfare", "growth")


@dataclass(frozen=True)
class DraftInput:
    text: str
    baseline_release_id: str
    knowledge_cutoff: str  # RFC 3339 with offset (the baseline release's cutoff)
    operation_key: str  # 32-64 hex chars, derived from (actor, Idempotency-Key)


@dataclass
class DraftResult:
    status: str
    draft_spec: dict[str, Any] | None
    candidate_spec: dict[str, Any] | None
    validation: dict[str, Any]
    restatement: str
    language: str
    llm_restatement: str
    unsupported: list[dict[str, Any]]
    rejected_ids: list[dict[str, Any]]
    missing_fields: list[str]
    assumptions_added: list[dict[str, Any]]
    numbers_to_confirm: list[dict[str, Any]]
    provider: str
    model: str
    model_requested: str
    prompt_version: str
    prompt_sha256: str
    catalog_digest: str
    usage: dict[str, Any]
    latency_ms: float
    fallback_from: list[dict[str, Any]] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    text_sha256: str = ""
    text_length: int = 0
    draft_spec_sha256: str | None = None  # sha256 of the canonical bytes POST /v1/scenarios will store
    parameters_set: list[dict[str, Any]] = field(default_factory=list)  # every parameter the LLM set

    def as_json(self) -> dict[str, Any]:
        return {
            "status": self.status,
            "confirmation_required": True,
            "executed": False,
            "draft_spec": self.draft_spec,
            "draft_spec_sha256": self.draft_spec_sha256,
            "candidate_spec": self.candidate_spec,
            "validation": self.validation,
            "restatement": self.restatement,
            "language": self.language,
            "llm_restatement": self.llm_restatement,
            "unsupported": self.unsupported,
            "rejected_ids": self.rejected_ids,
            "missing_fields": self.missing_fields,
            "assumptions_added": self.assumptions_added,
            "numbers_to_confirm": self.numbers_to_confirm,
            "parameters_set": self.parameters_set,
            "provider": self.provider,
            "model": self.model,
            "model_requested": self.model_requested,
            "prompt_version": self.prompt_version,
            "prompt_sha256": self.prompt_sha256,
            "catalog_digest": self.catalog_digest,
            "usage": self.usage,
            "latency_ms": self.latency_ms,
            "fallback_from": self.fallback_from,
            "warnings": self.warnings,
            "next_step": "Review the draft and its numbers. Nothing has run. To run it, submit draft_spec "
                         "unchanged (or edited) to POST /v1/scenarios, then POST /v1/scenarios/{id}/runs.",
        }


def text_digest(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def build_request(text: str, catalog: DraftCatalog, budget: LlmBudget) -> LlmRequest:
    return LlmRequest(system_prompt=system_prompt(catalog), user_content=user_envelope(text),
                      output_schema=output_schema(catalog), schema_name=SCHEMA_NAME,
                      max_output_tokens=budget.max_output_tokens, prompt_version=PROMPT_VERSION,
                      text_sha256=text_digest(text))


# --------------------------------------------------------------------------- provider calls
async def call_providers(request: LlmRequest, drafters: Sequence[ScenarioDrafter], ledger: LlmLedger,
                         operation_key: str) -> tuple[LlmResponse, list[dict[str, Any]]]:
    """Primary provider, then the fallback on retryable failures only. Every attempt is budgeted."""
    if not drafters:
        from reva.nl.ports import LlmUnavailable

        raise LlmUnavailable("no LLM provider is configured", reason="no_provider")
    tokens = token_upper_bound(request)
    failures: list[dict[str, Any]] = []
    last: LlmProviderError | None = None
    for attempt, drafter in enumerate(drafters):
        op = f"nl_draft:{operation_key}:{attempt}"
        # BudgetExhausted propagates: never a fallback, nothing sent
        await asyncio.to_thread(ledger.reserve, op, requests=1, tokens=tokens)
        try:
            response = await drafter.complete(request)
        except LlmProviderError as e:
            used = (e.details.get("usage") or {}).get("total_tokens")
            # unknown usage stays charged at the reserved upper bound (fail closed)
            await asyncio.to_thread(ledger.settle, op, requests=1, tokens=int(used) if used else tokens)
            failures.append({"provider": drafter.provider, "model": drafter.model,
                             "reason": e.details.get("reason"), "retryable": e.retryable})
            last = e
            if not e.retryable:
                raise
            continue
        await asyncio.to_thread(ledger.settle, op, requests=1, tokens=response.usage.total_tokens or tokens)
        return response, failures
    assert last is not None
    raise LlmProviderError("every configured LLM provider failed; no draft was produced", retryable=True,
                           reason="all_providers_failed", attempts=failures)


# --------------------------------------------------------------------------- interpretation
def _s(v: Any, n: int = MAX_STR) -> str:
    return str(v)[:n] if v is not None else ""


def _check_output(output: Any, catalog: DraftCatalog) -> dict[str, Any]:
    if not isinstance(output, dict):
        raise LlmProviderError("LLM output is not a JSON object", reason="output_invalid")
    v = jsonschema.Draft202012Validator(output_schema(catalog))
    errors = sorted(v.iter_errors(output), key=lambda e: list(e.path))
    if errors:
        raise LlmProviderError("LLM output does not match the drafting schema", reason="output_invalid",
                               errors=[{"path": "/" + "/".join(map(str, e.path)), "message": e.message[:200]}
                                       for e in errors[:10]])
    for key in ("countries", "outputs", "parameters", "unsupported", "assumptions_added"):
        if len(output[key]) > MAX_LIST:
            raise LlmProviderError(f"LLM output list {key} is longer than {MAX_LIST}", reason="output_invalid")
    return output


def _gap(catalog: DraftCatalog, key: str, text: str, reason: str, source: str) -> dict[str, Any]:
    norm = catalog.normalize_gap(key)
    known = norm is not None
    g = catalog.gap_keys.get(norm if norm is not None else "nl.unclassified")
    assert g is not None
    item: dict[str, Any] = {"text": _s(text, 500), "capability_key": g.key, "kind": g.kind, "reason": _s(reason, 500),
            "source": source}
    if not known:
        item["llm_capability_key_rejected"] = True
    return item


def _set_path(doc: dict[str, Any], path: str, value: Any) -> None:
    parts = path.split(".")
    cur: Any = doc
    for i, part in enumerate(parts):
        m = re.match(r"^([a-z0-9_]+)(?:\[(\d+)\])?$", part)
        assert m is not None
        name, idx = m.group(1), m.group(2)
        last = i == len(parts) - 1
        if idx is None:
            if last:
                cur[name] = value
            else:
                cur = cur.setdefault(name, {})
        else:
            lst = cur.setdefault(name, [])
            k = int(idx)
            while len(lst) <= k:
                lst.append({} if not last else None)
            if last:
                lst[k] = value
            else:
                if not isinstance(lst[k], dict):
                    lst[k] = {}
                cur = lst[k]


def _fill_defaults(node: Mapping[str, Any], value: Any) -> Any:
    """Fill schema constants and empty arrays for absent required members (never a guessed number)."""
    if not isinstance(node, Mapping):
        return value
    if _const(node)[0]:
        return _const(node)[1] if value is None else value
    if node.get("type") == "object" or "properties" in node:
        out = dict(value) if isinstance(value, dict) else {}
        props = node.get("properties") or {}
        for name in props:
            sub = props.get(name) or {}
            if name in out:
                out[name] = _fill_defaults(sub, out[name])
                continue
            if name not in (node.get("required") or []):
                continue  # optional members stay absent (the model's own default applies)
            if _const(sub)[0]:
                out[name] = _const(sub)[1]
            elif sub.get("type") == "object" or "properties" in sub:
                out[name] = _fill_defaults(sub, {})
            elif sub.get("type") == "array":
                out[name] = []
        return out
    if node.get("type") == "array" and isinstance(value, list):
        items = node.get("items") or {}
        return [_fill_defaults(items, v) for v in value]
    return value


def _missing_leaves(node: Mapping[str, Any], value: Any, prefix: str) -> list[str]:
    """Required non-constant leaves the draft does not set (they are asked for, never guessed)."""
    if not (node.get("type") == "object" or "properties" in node):
        return [] if value is not None else [prefix]
    if not isinstance(value, dict):
        return [prefix]
    out: list[str] = []
    props = node.get("properties") or {}
    for name in node.get("required") or []:
        sub = props.get(name) or {}
        if name not in value:
            out.append(f"{prefix}.{name}")
        elif isinstance(sub, dict) and (sub.get("type") == "object" or "properties" in sub):
            out.extend(_missing_leaves(sub, value[name], f"{prefix}.{name}"))
        elif isinstance(sub, dict) and value[name] == [] and int(sub.get("minItems") or 0) > 0:
            out.append(f"{prefix}.{name}")
    return out


def _apply_conditionals(branch: Mapping[str, Any], spec: dict[str, Any], explicit: set[str]) -> None:
    """Apply ``allOf: [{if, then}]`` constants for fields the LLM did not set (e.g. L1 -> fixed quantities)."""
    for clause in branch.get("allOf") or []:
        cond, then = clause.get("if"), clause.get("then")
        if not isinstance(cond, dict) or not isinstance(then, dict):
            continue
        if not jsonschema.Draft202012Validator(cond).is_valid(spec):
            continue
        _apply_then(then, spec, "", explicit)


def _apply_then(node: Mapping[str, Any], value: dict[str, Any], prefix: str, explicit: set[str]) -> None:
    for name, sub in (node.get("properties") or {}).items():
        path = f"{prefix}.{name}" if prefix else name
        if not isinstance(sub, dict):
            continue
        if "const" in sub and not any(p == path or p.startswith(path + "[") for p in explicit):
            value[name] = sub["const"]
        elif isinstance(sub.get("properties"), dict) and isinstance(value.get(name), dict):
            _apply_then(sub, value[name], path, explicit)


def _default_fidelity(model: DraftableModel) -> str | None:
    if "L1" in model.fidelities:
        return "L1"
    return next((f for f in model.fidelities if f != "L0"), model.fidelities[0] if model.fidelities else None)


def _walk_numbers(doc: Any, prefix: str = "") -> list[tuple[str, float]]:
    out: list[tuple[str, float]] = []
    if isinstance(doc, dict):
        for k, v in doc.items():
            out.extend(_walk_numbers(v, f"{prefix}.{k}" if prefix else k))
    elif isinstance(doc, list):
        for i, v in enumerate(doc):
            out.extend(_walk_numbers(v, f"{prefix}[{i}]"))
    elif isinstance(doc, (int, float)) and not isinstance(doc, bool):
        out.append((prefix, float(doc)))
    return out


def interpret(response: LlmResponse, text: str, inp: DraftInput, catalog: DraftCatalog,
              *, now: datetime | None = None) -> DraftResult:
    """Turn an (untrusted) LLM output into a checked draft. Pure apart from the registries."""
    from reva.simulation.spec import validate_scenario_spec

    base: dict[str, Any] = dict(provider=response.provider, model=response.model,
                                model_requested=response.model_requested,
                prompt_version=PROMPT_VERSION, prompt_sha256=prompt_digest(catalog),
                catalog_digest=catalog.digest(), usage={**response.usage.as_json(), "requests": 1},
                latency_ms=response.latency_ms, text_sha256=text_digest(text), text_length=len(text))
    warnings: list[str] = []
    if response.recorded:
        warnings.append("recorded_llm_response: replayed from a test fixture, not a live provider call")
    if response.output is None:
        reason = response.refusal or "the provider returned no draft"
        unsupported = [_gap(catalog, "nl.out_of_scope", text[:200], f"no draft: {reason}", "provider")]
        return DraftResult(status="nothing_draftable", draft_spec=None, candidate_spec=None,
                           validation={"valid": False, "errors": []}, restatement=_restate_none("en", unsupported),
                           language="en", llm_restatement="", unsupported=unsupported, rejected_ids=[],
                           missing_fields=[], assumptions_added=[], numbers_to_confirm=[], warnings=warnings, **base)
    out = _check_output(response.output, catalog)
    lang = out["input_language"] if out["input_language"] in ("fr", "en") else "en"
    unsupported = [_gap(catalog, _s(u["capability_key"], 100), u["text"], u["reason"], "llm")
                   for u in out["unsupported"]]
    plugin_state, registry = registered_plugins()
    registered = set(registry) if plugin_state == "registered" else set(catalog.models)
    present = {u["capability_key"] for u in unsupported}
    for hit in keyword_gaps(text, language=lang, registered=registered,
                            multi_period_available=catalog.horizon_multi_period):
        gk = catalog.normalize_gap(hit.capability_key)
        if gk is not None and gk not in present:
            unsupported.append(_gap(catalog, gk, hit.text, hit.reason, "server_guard"))
            present.add(gk)
    assumptions = [{"text": _s(a, 500), "source": "llm"} for a in out["assumptions_added"]]
    rejected: list[dict[str, Any]] = []
    missing: list[str] = []
    key = _s(out["model_key"], 100).strip()
    common: dict[str, Any] = dict(llm_restatement=_s(out["request_restatement"], 2000), language=lang,
                                  warnings=warnings,
                  assumptions_added=assumptions, **base)
    if not key:
        if not unsupported:
            unsupported.append(_gap(catalog, "nl.out_of_scope", text[:200],
                                    "no registered model matches the request", "server"))
        return DraftResult(status="nothing_draftable", draft_spec=None, candidate_spec=None,
                           validation={"valid": False, "errors": []}, restatement=_restate_none(lang, unsupported),
                           unsupported=unsupported, rejected_ids=[], missing_fields=[], numbers_to_confirm=[],
                           **common)
    model = catalog.models.get(key)
    if model is None:
        rejected.append({"field": "model_key", "value": key[:100]})
        gap_key = catalog.model_gap(key) or "nl.unclassified"
        if gap_key not in present:
            unsupported.append(_gap(catalog, gap_key, key, "model is not registered for drafting", "server"))
        return DraftResult(status="draft_rejected", draft_spec=None, candidate_spec=None,
                           validation={"valid": False, "errors": []},
                           restatement=_restate_rejected(lang, rejected, unsupported), unsupported=unsupported,
                           rejected_ids=rejected, missing_fields=[], numbers_to_confirm=[], **common)
    if model.experimental:
        warnings.append(f"experimental_model: {model.model_key} is not yet reviewed ({model.review_status})")

    spec: dict[str, Any] = {}
    explicit: set[str] = set()
    # countries
    countries: list[str] = []
    for c in out["countries"]:
        code = _s(c, 10).strip().upper()
        if code in model.countries:
            if code not in countries:
                countries.append(code)
        else:
            rejected.append({"field": "countries", "value": code})
            unsupported.append(_gap(catalog, "geography.not_covered", code,
                                    f"{code} is not in {model.model_key}'s countries {list(model.countries)}",
                                    "server"))
    if not countries and not any(r["field"] == "countries" for r in rejected):
        missing.append("countries")
    # outputs
    outputs: list[str] = []
    for o in out["outputs"]:
        oid = _s(o, 100).strip()
        if oid in model.outputs:
            if oid not in outputs:
                outputs.append(oid)
        else:
            rejected.append({"field": "outputs", "value": oid})
            macro = oid in model.not_computed or any(h in oid.lower() for h in MACRO_OUTPUT_HINTS)
            gk = "outputs.macroeconomic" if macro and "outputs.macroeconomic" in catalog.gap_keys else "nl.unclassified"
            unsupported.append(_gap(catalog, gk, oid, f"{oid} is not an output of {model.model_key}", "server"))
    if not out["outputs"]:
        outputs = list(model.outputs)
        assumptions.append({"text": "outputs: all outputs of the model (none named)", "source": "server"})
    # fidelity
    fid = out["fidelity"]
    if fid is None:
        fid = _default_fidelity(model)
        if fid is not None:
            assumptions.append({"text": f"fidelity {fid} (not stated)", "source": "server"})
    else:
        fid = _s(fid, 10).strip().upper()
        if fid not in model.fidelities:
            rejected.append({"field": "fidelity", "value": fid})
            gk = f"fidelity.{fid}" if f"fidelity.{fid}" in catalog.gap_keys else "nl.unclassified"
            unsupported.append(_gap(catalog, gk, fid, f"fidelity {fid} is not available for {model.model_key}",
                                    "server"))
        explicit.add("fidelity")
    # reference year
    year = out["reference_year"]
    year_source = "llm"
    if year is None and "reference_year" in (model.branch.get("required") or []):
        missing.append("reference_year")  # asked for, never defaulted
    # parameters
    param_meta: dict[str, dict[str, Any]] = {}
    for p in out["parameters"]:
        path = _s(p["path"], 200).strip()
        spec_p = model.param(path) if _PATH.match(path) else None
        if spec_p is None:
            rejected.append({"field": "parameters", "value": path[:200]})
            unsupported.append(_gap(catalog, "nl.parameter_not_draftable", path,
                                    f"{path} is not a parameter of {model.model_key}", "server"))
            continue
        if any(int(i) > MAX_INDEX for i in re.findall(r"\[(\d+)\]", path)):
            rejected.append({"field": "parameters", "value": path})
            continue
        if spec_p.kind in ("number", "integer"):
            value: Any = p["number"]
            if value is None or isinstance(value, bool) or (spec_p.kind == "integer" and value != int(value)):
                rejected.append({"field": "parameters", "value": path, "reason": f"{spec_p.kind} expected"})
                continue
            value = int(value) if spec_p.kind == "integer" else value
        elif spec_p.kind == "choice":
            value = p["text"] if p["text"] is not None else p["number"]
            if value not in spec_p.choices:
                rejected.append({"field": "parameters", "value": f"{path}={_s(value, 50)}"})
                continue
        elif spec_p.kind == "boolean":
            value = {"true": True, "false": False}.get(_s(p["text"]).lower())
            if value is None:
                rejected.append({"field": "parameters", "value": path, "reason": "boolean expected"})
                continue
        else:
            value = _s(p["text"], 200)
        _set_path(spec, path, value)
        explicit.add(path)
        param_meta[path] = {"quote": _s(p["quote"], 300)}

    title = _s(out["title"], 120).strip() or f"Draft: {model.model_key}"
    spec.update({
        "title": title,
        "baseline_release_id": inp.baseline_release_id,
        "knowledge_cutoff": inp.knowledge_cutoff,
        "model_key": model.model_key,
        "countries": countries,
        "outputs": outputs,
        "seed": DEFAULT_SEED,
    })
    if model.schema_version is not None:
        spec["schema_version"] = model.schema_version
    if model.model_version is not None:
        spec["model_version"] = model.model_version
    if fid is not None:
        spec["fidelity"] = fid
    if year is not None:
        spec["reference_year"] = year
    branch_props = model.branch.get("properties") or {}
    for name in model.branch.get("required") or []:
        sub = branch_props.get(name) or {}
        if name not in spec:
            if _const(sub)[0]:
                spec[name] = _const(sub)[1]
            elif isinstance(sub.get("enum"), list) and name == "missing_input_policy":
                spec[name] = "fail" if "fail" in sub["enum"] else sub["enum"][0]
                assumptions.append({"text": f"missing_input_policy {spec[name]}", "source": "server"})
            elif sub.get("type") == "object" or "properties" in sub:
                spec[name] = {}
    _apply_conditionals(model.branch, spec, explicit)
    for name, sub in branch_props.items():
        if name in spec and isinstance(sub, dict) and (sub.get("type") == "object" or "properties" in sub):
            spec[name] = _fill_defaults(sub, spec[name])
    for name in ("schema_version", "model_version"):
        if name not in spec and name in branch_props:
            missing.append(name)
    for name in model.branch.get("required") or []:
        if name not in SERVER_FIELDS and name not in EXPLICIT_FIELDS and isinstance(branch_props.get(name), dict):
            missing.extend(_missing_leaves(branch_props[name], spec.get(name), name))

    # numbers to confirm (every number in the model-specific parts + the reference year)
    numbers = stated_numbers(text)
    confirm: list[dict[str, Any]] = []
    if "reference_year" in spec:
        confirm.append({"path": "reference_year", "value": spec["reference_year"],
                        "provenance": "server_default" if year_source == "server_default"
                        else number_provenance(float(spec["reference_year"]), numbers)})
    for name in spec:
        if name in ("reference_year", "seed") or not isinstance(spec[name], (dict, list)):
            continue
        for path, v in _walk_numbers(spec[name], name):
            if path in explicit:
                prov = number_provenance(v, numbers)
                item = {"path": path, "value": spec_value(spec, path), "provenance": prov,
                        "quote": param_meta.get(path, {}).get("quote", "")}
                if prov == "not_in_text":
                    warnings.append(f"number_not_in_text: {path} was proposed by the LLM, not written by the user")
            else:
                item = {"path": path, "value": spec_value(spec, path), "provenance": "schema_constant"}
            confirm.append(item)

    candidate = copy.deepcopy(spec)
    errors: list[dict[str, Any]] = []
    valid = False
    canonical_sha: str | None = None
    if not rejected:
        try:
            parsed = validate_scenario_spec(spec, now=now)
            if plugin_state == "registered" and model.model_key in registry:
                registry[model.model_key].validate(spec)
            if hasattr(parsed, "as_json") and hasattr(parsed, "canonical_bytes"):
                spec = parsed.as_json()  # exactly what POST /v1/scenarios stores
                canonical_sha = hashlib.sha256(parsed.canonical_bytes()).hexdigest()
            valid = True
        except (ValidationProblem, CapabilityGap) as e:
            errors = [{"code": e.code, "message": e.message[:300]}]
            errors += [{"path": d.get("path"), "message": _s(d.get("message"), 300)}
                       for d in (e.details.get("errors") or [])[:20] if isinstance(d, dict)]
            cap = e.details.get("capability")
            if isinstance(cap, str) and cap in catalog.gap_keys and cap not in present:
                unsupported.append(_gap(catalog, cap, cap, e.message, "validator"))
    def _is_missing(e: Mapping[str, Any]) -> bool:
        where = str(e.get("path") or "").strip("/").replace("/", ".")
        return "required property" in str(e.get("message", "")) or any(
            where == m or where.startswith(m + ".") for m in missing)

    details = [e for e in errors if "path" in e]
    only_missing = bool(details) and all(_is_missing(e) for e in details)
    if rejected:
        status = "draft_rejected"
    elif valid:
        status = "draft_ready"
    elif missing and only_missing:
        status = "needs_input"
    else:
        status = "draft_invalid"
    result = DraftResult(
        status=status, draft_spec=spec if status == "draft_ready" else None,
        candidate_spec=None if status in ("draft_ready", "draft_rejected") else candidate,
        validation={"valid": status == "draft_ready", "errors": errors,
                    "validator": "reva.simulation.spec.validate_scenario_spec"},
        restatement="", unsupported=unsupported, rejected_ids=rejected, missing_fields=missing,
        numbers_to_confirm=confirm, draft_spec_sha256=canonical_sha if status == "draft_ready" else None,
        parameters_set=[{"path": p, "value": spec_value(spec if valid else candidate, p),
                         "quote": param_meta.get(p, {}).get("quote", "")} for p in sorted(param_meta)],
        **common)
    result.restatement = restate(result, model)
    return result


def spec_value(spec: Mapping[str, Any], path: str) -> Any:
    cur: Any = spec
    for part in path.split("."):
        m = re.match(r"^([A-Za-z0-9_]+)((?:\[\d+\])*)$", part)
        if m is None:
            return None
        cur = cur.get(m.group(1)) if isinstance(cur, Mapping) else None
        for idx in re.findall(r"\[(\d+)\]", m.group(2)):
            cur = cur[int(idx)] if isinstance(cur, list) and int(idx) < len(cur) else None
    return cur


# --------------------------------------------------------------------------- restatement (server-generated)
def _gaps_text(lang: str, unsupported: Sequence[Mapping[str, Any]]) -> str:
    if not unsupported:
        return ""
    items = "; ".join(f"{u['text']} ({u['capability_key']})" for u in unsupported[:10])
    return (f" Non pris en charge : {items}." if lang == "fr" else f" Not supported: {items}.")


def _restate_none(lang: str, unsupported: Sequence[Mapping[str, Any]]) -> str:
    if lang == "fr":
        return "Aucun brouillon de scénario n'a pu être établi : aucun modèle enregistré ne calcule cette " \
               "demande." + _gaps_text(lang, unsupported) + " Rien n'a été exécuté."
    return "No scenario draft could be made: no registered model computes this request." + \
        _gaps_text(lang, unsupported) + " Nothing was run."


def _restate_rejected(lang: str, rejected: Sequence[Mapping[str, Any]], unsupported: Sequence[Mapping[str, Any]]
                      ) -> str:
    ids = ", ".join(f"{r['field']}={r['value']}" for r in rejected[:10])
    if lang == "fr":
        return (f"Brouillon rejeté : il fait référence à des identifiants hors de la liste autorisée ({ids}). "
                "Rien n'a été remplacé ni exécuté ; reformulez la demande sans ces éléments."
                + _gaps_text(lang, unsupported))
    return (f"Draft rejected: it references identifiers outside the allow-list ({ids}). Nothing was substituted "
            "or run; rephrase the request without them." + _gaps_text(lang, unsupported))


def restate(r: DraftResult, model: DraftableModel) -> str:
    """Deterministic plain-language restatement of what the server will submit (French or English)."""
    lang = r.language
    if r.status == "draft_rejected":
        return _restate_rejected(lang, r.rejected_ids, r.unsupported)
    spec = r.draft_spec or r.candidate_spec or {}
    countries = ", ".join(spec.get("countries") or []) or ("(aucun pays)" if lang == "fr" else "(no country)")
    nums = "; ".join(f"{p['path']} = {p['value']}" for p in r.parameters_set)
    outs = list(spec.get("outputs") or [])
    outputs = ", ".join(outs[:6]) + (f" (+{len(outs) - 6})" if len(outs) > 6 else "")
    if lang == "fr":
        head = {"draft_ready": "Brouillon valide (non exécuté)", "needs_input": "Brouillon incomplet",
                "draft_invalid": "Brouillon non valide"}[r.status]
        year = spec.get("reference_year") or "(non précisée)"
        text = (f"{head} : modèle {model.model_key}, pays {countries}, année de référence "
                f"{year}, fidélité {spec.get('fidelity')}"
                + (f" ; paramètres : {nums}" if nums else "") + f" ; sorties : {outputs}.")
        if r.missing_fields:
            text += f" Informations manquantes : {', '.join(r.missing_fields)}."
        if r.validation.get("errors") and r.status == "draft_invalid":
            text += " Refusé par le validateur : " + "; ".join(e["message"] for e in r.validation["errors"][:5]) + "."
        text += _gaps_text(lang, r.unsupported)
        return text + " Vérifiez chaque valeur ; rien ne s'exécute sans votre confirmation."
    head = {"draft_ready": "Valid draft (not run)", "needs_input": "Incomplete draft",
            "draft_invalid": "Invalid draft"}[r.status]
    year = spec.get("reference_year") or "(not stated)"
    text = (f"{head}: model {model.model_key}, countries {countries}, reference year {year}, "
            f"fidelity {spec.get('fidelity')}" + (f"; parameters: {nums}" if nums else "") + f"; outputs: {outputs}.")
    if r.missing_fields:
        text += f" Missing information: {', '.join(r.missing_fields)}."
    if r.validation.get("errors") and r.status == "draft_invalid":
        text += " Rejected by the validator: " + "; ".join(e["message"] for e in r.validation["errors"][:5]) + "."
    text += _gaps_text(lang, r.unsupported)
    return text + " Check every value; nothing runs without your confirmation."


# --------------------------------------------------------------------------- entry point
async def draft_scenario(inp: DraftInput, *, drafters: Sequence[ScenarioDrafter], ledger: LlmLedger,
                         budget: LlmBudget, catalog: DraftCatalog | None = None,
                         now: datetime | None = None) -> DraftResult:
    """Draft a scenario from text. Raises ``budget_exhausted`` (429) before any provider call when over budget."""
    text = sanitize_text(inp.text)
    if not re.fullmatch(r"[0-9a-f]{32,64}", inp.operation_key):
        raise ValueError("operation_key must be 32-64 lowercase hex characters")
    catalog = catalog or current_catalog()
    request = build_request(text, catalog, budget)
    response, failures = await call_providers(request, drafters, ledger, inp.operation_key)  # may raise 429
    result = interpret(response, text, inp, catalog, now=now)
    result.fallback_from = failures
    if failures:
        result.warnings.append(f"fallback_provider: {response.provider} answered after "
                               f"{', '.join(f['provider'] for f in failures)} failed")
    return result
