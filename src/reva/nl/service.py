"""Natural language -> draft ScenarioSpec: the server-side pipeline around the LLM.

Order of operations (nothing is executed, nothing is stored except the budget
ledger rows and, in the API, one audit row without the text):

1. sanitize the text (NFC, controls removed, <= 4096 UTF-8 bytes);
2. build the fixed request: system prompt + trusted catalogue, the text as a
   JSON data field, a structural output schema;
3. reserve budget (one request + a token upper bound) — over budget raises
   ``budget_exhausted`` before anything is sent;
4. call the primary provider; on a *retryable* provider failure (transport,
   429, 5xx) and only then, reserve again and call the fallback provider;
   configuration errors (401/403/404/400) are raised, never masked;
5. settle the ledger with the provider-reported usage;
6. validate the output against the output schema (untrusted JSON);
7. allow-list checks: model key, countries, outputs, parameter paths/choices
   and fidelity must be catalogue ids — a draft referencing anything else is
   **rejected** (no substitution, no dropping);
8. compose the full spec (server fields: schema/model version, baseline
   release, knowledge cutoff, seed; constants from the schema), then run the
   same validator as hand-written specs (``validate_scenario_spec`` and the
   registered plugin's ``validate``);
9. deterministic checks on the text add typed gaps the LLM may have missed;
10. every number is listed for confirmation with its provenance, and the
    restatement is generated by the server from the validated spec (the LLM's
    own paraphrase is returned separately, labelled).
"""

